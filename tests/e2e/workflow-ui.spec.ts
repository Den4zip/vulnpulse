    await input.fill('2001-01-01T00:00')
    await app.evaluate(() => { (globalThis as any).__slaNow = Date.parse('2000-01-01T00:00:01.001Z') })
    expect(await page.evaluate(() => window.electronAPI.sla.get(1))).toMatchObject({ ok: true, value: { record: { state: 'overdue', revision: 1 } } })
