async function selectOwner(page: Page, index = 0) {
  await page.getByRole('button', { name: `Выбрать CVE-2026-${10000 + index}`, exact: true }).click()
  await expect(page.locator('#workflow-owner-heading')).toHaveText(`CVE-2026-${10000 + index}`)
}
async function addNote(page: Page, body: string) {
  await page.getByRole('button', { name: 'Добавить заметку', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Текст заметки', { exact: true }).fill(body)
  await dialog.getByRole('button', { name: 'Сохранить заметку', exact: true }).click()
  await expect(dialog).toHaveCount(0)
}

