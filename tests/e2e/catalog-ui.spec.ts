test('catalog UI observes menu import completion, reports import errors and cancels a pending file selection', async () => {
  const context = await launchCatalog()
  const { app, page } = context
  try {
    await expect(page.getByRole('heading', { name: 'Каталог пока пуст' })).toBeVisible()
    await app.evaluate(({ Menu }) => {
      const item = Menu.getApplicationMenu()!.getMenuItemById('osv-file')!
      item.click(item, undefined as any, undefined as any)
    })
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(3)
    await app.evaluate((_electron, path) => { (globalThis as any).__catalogTest.path = path }, resolve('examples/fstec-demo.xml'))
    await page.getByRole('button', { name: 'Импорт', exact: true }).click()
    await page.getByRole('button', { name: /OSV JSON/ }).click()
    await expect(page.getByRole('alert')).toHaveText('Файл не импортирован. Проверьте формат и доступность файла.')
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(3)
    await app.evaluate((_electron, path) => {
      const state = (globalThis as any).__catalogTest
      state.path = path; state.holdPicker = true
    }, resolve('examples/osv-demo.json'))
    await page.getByRole('button', { name: 'Импорт', exact: true }).click()
    await page.getByRole('button', { name: /OSV JSON/ }).click()
    await expect.poll(() => app.evaluate(() => (globalThis as any).__catalogTest.pickers.length)).toBe(1)
    await expect(page.getByText('Выберите локальный файл…', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Импорт', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Отменить', exact: true }).click()
    await expect(page.locator('.operation-strip')).toContainText('Запрошена отмена.')
    await app.evaluate(() => { const state = (globalThis as any).__catalogTest; state.holdPicker = false; state.pickers.splice(0).forEach((resolve: () => void) => resolve()) })
    await expect(page.getByText('Импорт отменён.', { exact: true })).toBeVisible()
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(3)
    await expect(page.getByRole('button', { name: 'Импорт', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'О дизайне · Mint / Ali' }).click()
    await expect(page.getByRole('dialog').getByText(/CC BY 4.0/)).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'О дизайне · Mint / Ali' })).toBeFocused()
    expect(await app.evaluate(() => (globalThis as any).__catalogTest.unexpectedNetwork)).toBe(0)
  } finally {
    await app.evaluate(() => { (globalThis as any).__catalogTest.pickers.splice(0).forEach((resolve: () => void) => resolve()) }).catch(() => {})
    await app.close(); context.cleanup()
  }
})

test('catalog UI recovers from errors and ignores stale list/detail/write responses', async () => {
  const context = await launchCatalog()
  const { app, page } = context
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const state = (input: Record<string, unknown>) => app.evaluate((_electron, input) => { Object.assign((globalThis as any).__catalogTest, input) }, input)
  try {
    await expect(page.getByRole('heading', { name: 'Каталог пока пуст' })).toBeVisible()
    seedCatalog(context.dbPath, 6)
    await page.getByRole('button', { name: 'Обновить', exact: true }).click()
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(6)
    await state({ failList: true })
    await page.getByRole('button', { name: 'Обновить', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Не удалось выполнить операцию')
    await expect(page.locator('.catalog-count')).toHaveText('Недоступно')
    expect(await page.textContent('body')).not.toContain('private-provider-error')
    await state({ failList: false })
    await page.getByRole('button', { name: 'Повторить', exact: true }).click()
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(6)
    const search = page.getByRole('searchbox')
    await state({ holdSlow: true })
    await search.fill('slow')
    await expect.poll(() => app.evaluate(() => (globalThis as any).__catalogTest.slow.length)).toBe(1)
    await search.fill('fast')
    await expect(page.getByRole('button', { name: 'Открыть CVE-2026-10004', exact: true })).toBeVisible()
    await app.evaluate(() => { const state = (globalThis as any).__catalogTest; state.holdSlow = false; state.slow.splice(0).forEach((resolve: () => void) => resolve()) })
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(1)
    await expect(page.locator('.catalog-table tbody tr')).toContainText('fast fixture')
    await state({ holdGet: true })
    await page.getByRole('button', { name: 'Открыть CVE-2026-10004', exact: true }).click()
    await expect.poll(() => app.evaluate(() => (globalThis as any).__catalogTest.gets.length)).toBe(1)
    await expect(page.getByText('Загрузка карточки…', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await state({ holdGet: false })
    await search.fill('CVE-2026-10003')
    await page.getByRole('button', { name: 'Открыть CVE-2026-10003', exact: true }).click()
    await expect(page.locator('.detail-name')).toHaveText('slow fixture')
    await app.evaluate(() => (globalThis as any).__catalogTest.gets.splice(0).forEach((resolve: () => void) => resolve()))
    await expect(page.locator('.detail-name')).toHaveText('slow fixture')
    await page.keyboard.press('Escape')
    await search.fill('fast')
    await state({ failGet: true })
    await page.getByRole('button', { name: 'Открыть CVE-2026-10004', exact: true }).click()
    const detail = page.getByRole('dialog')
    await expect(detail.getByRole('alert')).toContainText('Не удалось выполнить операцию')
    await state({ failGet: false })
    await detail.getByRole('button', { name: 'Повторить' }).click()
    await expect(detail.locator('.detail-name')).toHaveText('fast fixture')
    await state({ failWrite: true })
    await detail.getByRole('combobox', { name: 'Новый статус' }).selectOption('Patched')
    await detail.getByRole('button', { name: 'Сохранить статус' }).click()
    await expect(detail.getByRole('alert')).toContainText('Сохранение не подтверждено')
    await expect(detail.getByRole('combobox', { name: 'Новый статус' })).toHaveValue('Patched')
    expect(await page.evaluate(() => window.electronAPI.vulnerabilities.list({ search: 'fast' }))).toMatchObject({ ok: true, value: { items: [{ status: 'New' }] } })
    await state({ failWrite: false, holdWrite: true })
    await detail.getByRole('button', { name: 'Сохранить статус' }).click()
    await expect.poll(() => app.evaluate(() => (globalThis as any).__catalogTest.writes.length)).toBe(1)
    await page.keyboard.press('Escape')
    await search.fill('CVE-2026-10003')
    await page.getByRole('button', { name: 'Открыть CVE-2026-10003', exact: true }).click()
    await expect(detail.locator('.detail-name')).toHaveText('slow fixture')
    await app.evaluate(() => { const state = (globalThis as any).__catalogTest; state.holdWrite = false; state.writes.splice(0).forEach((resolve: () => void) => resolve()) })
    await expect(detail.locator('.detail-name')).toHaveText('slow fixture')
    await expect(detail.getByRole('combobox', { name: 'Новый статус' })).toHaveValue('New')
    await page.keyboard.press('Escape')
    await search.fill('fast')
    await expect(page.locator('.catalog-table tbody tr').getByText('Исправлена', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Сбросить', exact: true }).click()
    await expect(page.locator('.catalog-table tbody tr')).toHaveCount(6)
    expect(errors).toEqual([])
    expect(await app.evaluate(() => (globalThis as any).__catalogTest.unexpectedNetwork)).toBe(0)
  } finally {
    await app.evaluate(() => {
      const state = (globalThis as any).__catalogTest
      state.slow.splice(0).forEach((resolve: () => void) => resolve())
      state.writes.splice(0).forEach((resolve: () => void) => resolve())
      state.gets.splice(0).forEach((resolve: () => void) => resolve())
    }).catch(() => {})
    await app.close(); context.cleanup()
  }
})
