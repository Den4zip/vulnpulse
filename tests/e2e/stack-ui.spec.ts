async function fillComponent(page: Page, name: string, product = 'ui-demo', version = '1.0.0') {
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название *', { exact: true }).fill(name)
  await dialog.getByLabel('Продукт (product) *', { exact: true }).fill(product)
  await dialog.getByLabel('Версия *', { exact: true }).fill(version)
  await dialog.getByLabel('PURL', { exact: true }).fill(`pkg:npm/${product}@${version}`)
}

function seedStack(path: string, count: number) {
  const db = new DatabaseSync(path)
  try {
    db.exec('BEGIN')
    const insert = db.prepare('INSERT INTO stack(kind,name,vendor,product,version,purl) VALUES(?,?,?,?,?,?)')
    for (let i = 0; i < count; i++) {
      const product = `stack-fixture-${i}`
      const name = i === 0 ? '<img src=x onerror="window.__stackXss=1">'
        : i === 1 ? 'Literal %_! component' : i === 2 ? 'slow fixture' : i === 3 ? 'fast fixture'
          : i === 4 ? 'Длинное имя '.repeat(100) : i === 5 ? 'Legacy without identifiers' : `Компонент ${String(i).padStart(3, '0')}`
      insert.run(['package', 'application', 'system'][i % 3], name, null, product, i === 5 ? null : '1.0.0', i === 5 ? null : `pkg:npm/${product}@1.0.0`)
    }
    db.exec('COMMIT')
  } catch (error) { db.exec('ROLLBACK'); throw error } finally { db.close() }
}

function fixtureWorkflow(path: string, stackId: number, otherId: number) {
  const db = new DatabaseSync(path)
  try {
    db.exec('PRAGMA foreign_keys=ON')
    const feed = db.prepare("INSERT INTO feeds(name,source) VALUES('osv','local:fixture') RETURNING id").get()!
    const vuln = db.prepare("INSERT INTO vulnerabilities(ext_id,feed_id,status) VALUES('UI-FIXTURE',?,'Affected') RETURNING id").get(feed.id)!
    db.prepare("INSERT INTO notes(vulnerability_id,body) VALUES(?,'keep note')").run(vuln.id)
    db.prepare("INSERT INTO sla(vulnerability_id,due_at) VALUES(?,'2026-12-01')").run(vuln.id)
    db.prepare('INSERT INTO matches(vulnerability_id,stack_id) VALUES(?,?)').run(vuln.id, stackId)
    db.prepare('INSERT INTO matches(vulnerability_id,stack_id) VALUES(?,?)').run(vuln.id, otherId)
  } finally { db.close() }
}
function counts(path: string) {
  const db = new DatabaseSync(path, { readOnly: true })
  try { return db.prepare(`SELECT (SELECT count(*) FROM matches) matches, (SELECT count(*) FROM vulnerabilities) cards,
    (SELECT count(*) FROM notes) notes, (SELECT count(*) FROM sla) sla`).get() } finally { db.close() }
}

